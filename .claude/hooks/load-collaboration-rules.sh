# SessionStart Hook - 협업 규칙 자동 로드
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
#
# 이 스크립트는 Claude 세션 시작 시 자동으로 CLAUDE.md를 읽어서
# Claude에게 프로젝트 협업 규칙을 전달합니다.
#
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

CLAUDE_MD="$CLAUDE_PROJECT_DIR/CLAUDE.md"

# CLAUDE.md 파일 존재 확인
if [ ! -f "$CLAUDE_MD" ]; then
    echo "⚠️  Warning: CLAUDE.md not found in project root."
    exit 0
fi

# 구분선과 함께 CLAUDE.md 내용 출력
cat << 'EOF'

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
📋 프로젝트 협업 규칙 (CLAUDE.md)
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

이 프로젝트는 다음 협업 규칙을 따릅니다.
세션 진행 중 항상 이 규칙들을 준수하세요.

EOF

# CLAUDE.md 내용 출력
cat "$CLAUDE_MD"

cat << 'EOF'

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

✅ 협업 규칙이 로드되었습니다.
   위 규칙들을 세션 동안 항상 준수해주세요.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

